import {publishedStats} from './lib/published-stats.mjs';
import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const origin = process.env.PREVIEW_URL || 'http://127.0.0.1:4322'
const out = new URL('../artifacts/about-open/', import.meta.url)
await mkdir(out, { recursive: true })
const browser = await chromium.launch(process.env.CI ? {} : { channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
  const published = await publishedStats(page, origin)
  await page.goto(origin + '/about/')
  await page.evaluate(() => document.fonts.ready)
  assert.equal(await page.locator('.protocol-code,.faq-n,.manifesto-types').count(), 0)
  assert.equal(await page.locator('.tool-note').count(), 16)
  assert.equal(await page.locator('.about-faqs details').count(), 4)
  assert((await page.locator('.about-intro-note').innerText()).includes(`${published.routes.length} 篇文章 · ${published.series} 个系列 · ${published.categories} 个分类`))
  await page.screenshot({ path: new URL('desktop.png', out).pathname })
  await page.locator('[data-name-poke]').click()
  assert.equal(await page.locator('[data-name-text]').innerText(), 'sleep4r')
  await page.locator('.tool-note summary').first().click()
  assert(await page.locator('.tool-note p').first().isVisible())
  await page.locator('.about-faqs summary').first().focus()
  await page.keyboard.press('Enter')
  assert(await page.locator('.about-faqs p').first().isVisible())
  await page.locator('.about-console > summary').click()
  assert(await page.locator('[data-shell-input]').isVisible())
  await page.locator('[data-cmd="whoami"]').click()
  assert.equal(await page.locator('[data-shell-out] > .block').count(), 1)
  await page.locator('[data-shell-input]').fill('<img src=x onerror=alert(1)>')
  await page.locator('[data-shell-input]').press('Enter')
  assert.equal(await page.locator('[data-shell-out] img').count(), 0)
  assert.match(await page.locator('[data-shell-out]').innerText(), /command not found: <img/)
  await page.locator('[data-shell-input]').fill('clear')
  await page.locator('[data-shell-input]').press('Enter')
  assert.equal(await page.locator('[data-shell-out]').innerText(), '')
  await page.locator('[data-shell-input]').fill('help')
  await page.locator('[data-shell-input]').press('Enter')
  assert.match(await page.locator('[data-shell-out]').innerText(), /whoami/)
  await page.locator('[data-cmd="whoami"]').evaluate(el => { if (el instanceof HTMLElement) for (let i = 0; i < 110; i++) el.click() })
  assert.equal(await page.locator('[data-shell-out] > *').count(), 100)
  await page.locator('[data-adbg] > summary').click()
  await page.locator('[data-adbg-btn]').click()
  assert.equal(await page.locator('[data-adbg-pid]').innerText(), '1337')
  assert.equal(await page.locator('[data-adbg-btn]').innerText(), 'detach debugger')
  await page.locator('[data-adbg-btn]').click()
  assert.equal(await page.locator('[data-adbg-pid]').innerText(), '0')
  for (const width of [320, 390, 640, 700, 768, 1000, 1280, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow ${width}`)
  }
  await page.setViewportSize({ width: 390, height: 1000 })
  await page.evaluate(() => scrollTo(0,0))
  await page.screenshot({ path: new URL('mobile.png', out).pathname })
  await page.locator('.about-intro-note a').first().click()
  await page.waitForURL('**/archive/**')
  await page.goBack()
  await page.waitForSelector('[data-name-poke]:not([hidden])')
  await page.locator('[data-name-poke]').click()
  assert.equal(await page.locator('[data-name-text]').innerText(), 'sleep4r')
  if (!(await page.locator('.about-console').evaluate(el => el.open))) await page.locator('.about-console > summary').click()
  const before = await page.locator('[data-shell-out] > .block').count()
  await page.locator('[data-cmd="whoami"]').click()
  assert.equal(await page.locator('[data-shell-out] > .block').count(), before + 1)
  const staticPage = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 390, height: 1000 } })
  await staticPage.goto(origin + '/about/')
  assert(await staticPage.locator('[data-name-static]').isVisible())
  assert(!await staticPage.locator('[data-name-poke]').isVisible())
  assert(!await staticPage.locator('[data-adbg]').isVisible())
  await staticPage.locator('.tool-note summary').first().click()
  assert(await staticPage.locator('.tool-note p').first().isVisible())
  await staticPage.locator('.about-faqs summary').first().click()
  assert(await staticPage.locator('.about-faqs p').first().isVisible())
  await staticPage.locator('.about-console > summary').click()
  assert(await staticPage.locator('[data-shell-out]').isVisible())
  assert(!await staticPage.locator('[data-shell-input]').isVisible())
  assert(!await staticPage.locator('[data-cmd]').first().isVisible())
  assert.equal(await staticPage.locator('.about-contacts a').count(), 2)
  assert.deepEqual(errors, [])
  await writeFile(new URL('verification.json', out), JSON.stringify({ widths: [320,390,640,700,768,1000,1280,1440], checks: ['Original tool tips and four FAQs preserved; native disclosures', 'Published counts and contact links', 'Name interaction restored', 'Terminal commands, clear, escaped unknown input, bounded output history', 'Debug simulation attach/detach', 'Client navigation and Back handlers run exactly once', 'No-JS native disclosures, static terminal, no inactive interactive controls'], errors, scope: 'Chrome automated checks; physical devices and aesthetic acceptance pending' }, null, 2))
  console.log('About: eight widths, disclosures, terminal, simulated debug, navigation and no-JS passed')
} finally { await browser.close() }
