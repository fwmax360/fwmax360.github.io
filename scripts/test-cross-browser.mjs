import {publishedStats} from './lib/published-stats.mjs';
import { webkit, firefox } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const origin = process.env.PREVIEW_URL || 'http://127.0.0.1:4322'
const out = new URL('../artifacts/cross-browser/', import.meta.url)
await mkdir(out, { recursive: true })
const routes = ['/', '/archive/', '/series/', '/map/', '/tags/', '/categories/Android/', '/about/', '/posts/arm64-calling-convention/']
const results = []
for (const engine of [webkit, firefox]) {
  const name = engine.name()
  const browser = await engine.launch()
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  const checks = []
  try {
    const published = await publishedStats(page, origin)
    for (const route of routes) {
      await page.goto(origin + route)
      await page.evaluate(() => document.fonts.ready)
      assert.equal(await page.locator('main h1').count(), 1, route)
      for (const width of [320, 390, 768, 1440]) {
        await page.setViewportSize({ width, height: 1000 })
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name} ${route} overflow ${width}`)
      }
      checks.push(`layout ${route}: 320/390/768/1440`)
    }
    await page.goto(origin)
    await page.setViewportSize({ width: 390, height: 1000 })
    await page.locator('[data-menu-toggle]').click()
    assert.equal(await page.locator('[data-menu-toggle]').getAttribute('aria-expanded'), 'true')
    await page.locator('#mobile-menu a[href="/tags"]').click()
    await page.waitForURL(/\/tags\/?$/)
    assert(!await page.locator('#mobile-menu').isVisible())
    await page.locator('[data-tag-query]').fill('Frida')
    assert.equal(await page.locator('[data-tag-item]:visible').count(), 1)
    await page.locator('[data-tag-clear]').click()
    assert.equal(await page.locator('[data-tag-item]:visible').count(), published.tags)
    await page.locator('[data-search-open]').click()
    assert(await page.locator('[data-search-input]').evaluate(el => el === document.activeElement))
    await page.locator('[data-search-input]').fill('Frida')
    await page.waitForSelector('[data-search] [role="option"]')
    assert(await page.locator('[data-search] [role="option"]').count() > 0)
    await page.keyboard.press('Escape')
    assert(!await page.locator('[data-search]').isVisible())
    checks.push('Mobile menu client navigation, tag filter and Pagefind search/Escape')
    await page.goto(origin + '/archive/')
    await page.waitForSelector('[data-archive-ready]')
    await page.locator('.archive-tools summary').click()
    await page.locator('#archive-category').selectOption('Android')
    assert.equal(await page.locator('[data-archive-item]:not([hidden])').count(), published.categoryCounts.Android)
    await page.locator('[data-density="compact"]').click()
    await page.reload()
    await page.waitForSelector('[data-archive-ready]')
    assert.equal(await page.locator('[data-archive-item]:not([hidden])').count(), published.categoryCounts.Android)
    assert.equal(await page.locator('[data-archive-density]').getAttribute('data-archive-density'), 'compact')
    await page.locator('.entry-title-link').first().click()
    await page.waitForURL('**/posts/**')
    await page.goBack()
    await page.waitForSelector('[data-archive-ready]')
    assert.equal(await page.locator('[data-archive-item]:not([hidden])').count(), published.categoryCounts.Android)
    checks.push('Archive URL category/density survives reload and article Back')
    await page.goto(origin + '/map/')
    await page.waitForSelector('[data-map-ready]')
    await page.locator('[data-map-query]').fill('no-matching-test-997')
    assert(await page.locator('[data-tree-empty]').isVisible())
    await page.locator('[data-map-clear]').click()
    assert.equal(await page.locator('.tree-post:not([hidden])').count(), published.routes.length)
    await page.locator('.tree-post a').first().focus()
    assert.equal(await page.locator('[data-inspector-link]').getAttribute('href'), await page.locator('.tree-post a').first().getAttribute('href'))
    checks.push('Mobile map filtering, reset and focus-linked preview')
    await page.goto(origin + '/posts/arm64-calling-convention/')
    assert(await page.locator('.prose td').evaluateAll(items => items.every(el => parseFloat(getComputedStyle(el).paddingTop) > 0)))
    await page.locator('.toc.mobile summary').click()
    const toc = page.locator('.toc.mobile [data-toc-link]').nth(1)
    const id = await toc.getAttribute('data-toc-link')
    await toc.click()
    await page.waitForFunction(id => document.getElementById(id) === document.activeElement, id)
    await page.goto(origin + '/posts/rc4/')
    await page.locator('.code-block[data-collapsible] [data-expand]').first().click()
    assert.equal(await page.locator('.code-block[data-collapsible]').first().getAttribute('data-open'), 'true')
    checks.push('Reader table padding, mobile TOC focus and code expansion')
    await page.goto(origin + '/about/')
    await page.locator('.tool-note summary').first().click()
    assert(await page.locator('.tool-note p').first().isVisible())
    await page.locator('.about-console > summary').click()
    assert.equal(await page.locator('summary .press-ripple').count(), 0, 'Native disclosures never acquire an overflowing ripple')
    await page.locator('[data-cmd="whoami"]').click()
    assert.equal(await page.locator('[data-shell-out] > .block').count(), 1)
    await page.waitForTimeout(750)
    await page.screenshot({ path: new URL(`${name}-about-mobile.png`, out).pathname })
    checks.push('About native disclosure without overflowing ripple and terminal command')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(origin)
    await page.evaluate(() => document.fonts.ready)
    const note = page.locator('[data-note-hover]').first()
    await note.scrollIntoViewIfNeeded()
    await page.waitForTimeout(150)
    await note.hover()
    await page.waitForSelector('[data-note-preview][data-visible]')
    assert.equal(await page.locator('[data-note-preview-image]').getAttribute('src'), await note.getAttribute('data-note-cover'))
    await page.waitForTimeout(350)
    await page.screenshot({ path: new URL(`${name}-hover-desktop.png`, out).pathname })
    checks.push('Desktop note preview uses actual cover')
    const staticPage = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 390, height: 1000 } })
    for (const route of routes) {
      await staticPage.goto(origin + route)
      assert.equal(await staticPage.locator('main h1').count(), 1)
      assert(await staticPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name} no-JS ${route}`)
    }
    await staticPage.goto(origin + '/silicon/')
    assert(await staticPage.locator('.scene-poster').isVisible())
    assert.equal(await staticPage.locator('canvas').count(), 0)
    checks.push('Eight routes without JS remain readable; silicon has static poster')
    const reduced = await browser.newPage({ reducedMotion: 'reduce', viewport: { width: 1440, height: 1000 } })
    await reduced.goto(origin)
    await reduced.evaluate(() => document.fonts.ready)
    await reduced.locator('[data-note-hover]').first().scrollIntoViewIfNeeded()
    await reduced.waitForTimeout(150)
    await reduced.locator('[data-note-hover]').first().hover()
    await reduced.waitForSelector('[data-note-preview][data-visible]')
    assert.equal(await reduced.locator('.note-preview-art').evaluate(el => getComputedStyle(el).transform), 'none')
    checks.push('Reduced-motion note preview is static')
    assert.deepEqual(errors, [], `${name} runtime errors`)
    results.push({ engine: name, version: browser.version(), checks, errors, scope: 'Playwright engine emulation; not physical iPhone or installed Safari; 3D rendering and clipboard are not covered' })
    console.log(`${name}: layout and critical interactions passed`)
  } catch (error) {
    await page.screenshot({ path: new URL(`${name}-failure.png`, out).pathname }).catch(() => {})
    results.push({ engine: name, checks, errors, failure: String(error), url: page.url() })
    throw error
  } finally {
    await writeFile(new URL('verification.json', out), JSON.stringify(results, null, 2))
    await browser.close()
  }
}
