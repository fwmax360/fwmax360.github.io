import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const origin = process.env.PREVIEW_URL || 'http://127.0.0.1:4322'
const out = new URL('../artifacts/taxonomy-open/', import.meta.url)
await mkdir(out, { recursive: true })
const browser = await chromium.launch(process.env.CI ? {} : { channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`) })
try {
  await page.goto(`${origin}/tags/`)
  await page.evaluate(() => document.fonts.ready)
  const terms = await page.locator('[data-tag-item]').evaluateAll(items => items.map(el => ({ href: el.getAttribute('href'), count: Number(el.querySelector('small').textContent) })))
  const categories = await page.locator('#categories a').evaluateAll(items => items.map(el => ({ href: el.getAttribute('href'), count: Number(el.querySelector('small').textContent) })))
  assert(terms.length > 0 && categories.length > 0)
  assert.equal(await page.locator('.signal-card,.term-index,.domain-card').count(), 0)
  await page.screenshot({ path: new URL('tags-desktop.png', out).pathname })
  const query = page.locator('[data-tag-query]')
  await query.fill('frida')
  assert.equal(await page.locator('[data-tag-item]:visible').count(), 1)
  assert.match(await page.locator('[data-tag-item]:visible').innerText(), /Frida/)
  assert.equal(await page.locator('[data-tag-count]').innerText(), '1')
  await query.fill('no-matching-fixture-993')
  assert(await page.locator('[data-tag-empty]').isVisible())
  assert.equal(await page.locator('[data-tag-group]:visible').count(), 0)
  await page.locator('[data-tag-clear]').click()
  assert.equal(await page.locator('[data-tag-item]:visible').count(), terms.length)
  assert(await query.evaluate(el => el === document.activeElement))
  await query.fill('platform')
  assert(await page.locator('[data-tag-item]:visible').count() > 0)
  assert.equal(await page.locator('[data-tag-group]:visible').count(), 1)
  await page.locator('[data-tag-clear]').click()
  for (const width of [320, 390, 640, 700, 768, 1000, 1280, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `tag index overflow ${width}`)
  }
  await page.setViewportSize({ width: 390, height: 1000 })
  await page.screenshot({ path: new URL('tags-mobile.png', out).pathname })
  await page.goto(`${origin}/archive/`)
  const published = await page.locator('.entry-title-link').evaluateAll(items => items.map(el => el.getAttribute('href')))
  const expectedByTopic = new Map()
  for (const route of published) {
    await page.goto(origin + route)
    const topics = await page.locator('.foot a[href^="/tags/"],.foot a[href^="/categories/"]').evaluateAll(items => [...new Set(items.map(el => el.getAttribute('href')))])
    for (const topic of topics) {
      const key = new URL(topic, origin).pathname.replace(/\/$/, '')
      const set = expectedByTopic.get(key) ?? new Set()
      set.add(route)
      expectedByTopic.set(key, set)
    }
  }
  // Check topic membership against the independently rendered published article footers.
  for (const topic of [...terms, ...categories]) {
    await page.goto(origin + topic.href)
    assert.equal(await page.locator('.topic-posts > li').count(), topic.count, topic.href)
    const hrefs = await page.locator('.topic-posts h2 a').evaluateAll(items => items.map(el => el.getAttribute('href')))
    assert.equal(new Set(hrefs).size, topic.count, `duplicate articles ${topic.href}`)
    assert(hrefs.every(href => href.startsWith('/posts/')))
    const key = new URL(topic.href, origin).pathname.replace(/\/$/, '')
    assert.deepEqual([...hrefs].sort(), [...(expectedByTopic.get(key) ?? [])].sort(), `membership ${topic.href}`)
    for (const width of [390, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `topic overflow ${topic.href} ${width}`)
    }
  }
  await page.goto(origin + categories[0].href)
  await page.screenshot({ path: new URL('category-desktop.png', out).pathname })
  await page.setViewportSize({ width: 390, height: 1000 })
  await page.screenshot({ path: new URL('category-mobile.png', out).pathname })
  await page.locator('.terms-back').click()
  await page.waitForURL('**/tags/**')
  await page.locator('[data-tag-query]').fill('frida')
  assert.equal(await page.locator('[data-tag-item]:visible').count(), 1)
  await page.locator('[data-tag-item]:visible').click()
  await page.waitForURL('**/tags/Frida**')
  await page.locator('.topic-posts h2 a').first().click()
  await page.waitForURL('**/posts/**')
  await page.goBack()
  await page.waitForSelector('.topic-posts')
  await page.locator('.terms-back').click()
  await page.waitForSelector('[data-tag-controls]:not([hidden])')
  await page.locator('[data-tag-query]').fill('no-matching-fixture-993')
  assert(await page.locator('[data-tag-empty]').isVisible())
  const staticPage = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 390, height: 1000 } })
  await staticPage.goto(`${origin}/tags/`)
  assert.equal(await staticPage.locator('[data-tag-item]:visible').count(), terms.length)
  assert(!await staticPage.locator('[data-tag-controls]').isVisible())
  await staticPage.goto(origin + categories[0].href)
  assert.equal(await staticPage.locator('.topic-posts > li').count(), categories[0].count)
  const reduced = await browser.newPage({ reducedMotion: 'reduce' })
  await reduced.goto(`${origin}/tags/`)
  await reduced.locator('[data-tag-item]').first().hover()
  assert.equal(await reduced.locator('[data-tag-item]').first().evaluate(el => getComputedStyle(el).transform), 'none')
  assert.deepEqual(errors, [])
  await writeFile(new URL('verification.json', out), JSON.stringify({ tagCount: terms.length, categories, checkedTopicPages: terms.length + categories.length, checks: ['Eight index widths and all topic pages at 390/1440: no overflow', 'Every tag/category article membership matches published article footers; counts and uniqueness', 'Keyword/group filtering, empty message, clear and keyboard focus', 'Client navigation to topic/article, Back and index script rebind', 'No-JS full vocabulary and category; inactive search hidden', 'Reduced motion no hover transforms'], errors, scope: 'Chrome automated checks, visual acceptance and physical devices pending' }, null, 2))
  console.log(`Taxonomy: ${terms.length} tags, ${categories.length} categories, full counts, filtering and progressive enhancement passed`)
} finally { await browser.close() }
